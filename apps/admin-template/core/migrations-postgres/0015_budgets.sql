-- banto-cost P4c (docs/project/design.md §3.3, spec §5.3, T09): budget
-- versions by phase × cost type.
--
-- A project has at most one draft at a time (budget_versions_one_draft). A
-- draft is edited freely; approving it gives it the next version number and
-- it is never rewritten afterwards. Version 1 is the original budget (当初予算),
-- the highest approved version the current one (現在の承認予算). A change
-- (version 2 on) carries its reason.
--
-- created_on is the date the budget rate (`budget_rate`) is resolved for
-- (design §10.2: 予算なら予算版の作成日). A draft's labor amounts are computed
-- on read; approval fixes the rate row, the rate and the amount per labor
-- line and the total. A later calc-basis change never rewrites an approved
-- version (design §10.5: 次の予算案から使う).
--
-- status MUST match `cost_domain::budget` (draft | approved), cost_type
-- `cost_domain::forecast::CostType`.
CREATE TABLE budget_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    version_no BIGINT,
    status TEXT NOT NULL CHECK (status IN ('draft','approved')),
    reason TEXT,
    created_on TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approved_at TEXT,
    total_amount BIGINT,
    row_version BIGINT NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (now()::text),
    updated_at TEXT NOT NULL DEFAULT (now()::text),
    CHECK ((status = 'draft' AND version_no IS NULL AND approved_at IS NULL
            AND total_amount IS NULL)
        OR (status = 'approved' AND version_no IS NOT NULL AND approved_at IS NOT NULL
            AND total_amount IS NOT NULL))
);

CREATE UNIQUE INDEX budget_versions_no ON budget_versions (project_id, version_no);
CREATE UNIQUE INDEX budget_versions_one_draft ON budget_versions (project_id)
    WHERE status = 'draft';

-- Labor lines carry planned minutes (amount fixed at approval); the other
-- cost types carry a planned amount. phase_id NULL = no phase (案件全体).
CREATE TABLE budget_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_version_id BIGINT NOT NULL REFERENCES budget_versions(id),
    line_no BIGINT NOT NULL,
    phase_id BIGINT REFERENCES phases(id),
    cost_type TEXT NOT NULL
        CHECK (cost_type IN ('labor','material','outsource','travel','other')),
    planned_minutes BIGINT,
    amount BIGINT,
    budget_rate BIGINT,
    applied_calc_value_id BIGINT REFERENCES calc_values(id),
    CHECK ((cost_type = 'labor' AND planned_minutes IS NOT NULL AND planned_minutes > 0)
        OR (cost_type <> 'labor' AND planned_minutes IS NULL AND amount IS NOT NULL
            AND amount >= 0 AND budget_rate IS NULL))
);

CREATE UNIQUE INDEX budget_lines_key
    ON budget_lines (budget_version_id, COALESCE(phase_id, 0), cost_type);
