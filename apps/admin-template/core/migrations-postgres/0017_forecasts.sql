-- banto-cost P5 (docs/project/design.md §3.4, spec §6.5・§6.6, T06・T28・T30):
-- completion forecast versions (完了見込版) by phase × cost type.
--
-- A project has at most one draft at a time (forecast_versions_one_draft).
-- A draft holds the base date (基準日), the planned end and the remaining
-- input (残工数・それ以外の見込み); its actuals and purchase-order remainders
-- are read as of the base date on every read. Adopting it (採用) gives it the
-- next version number and fixes, as one set for the same base date, the
-- actuals, the commitments, the forecast rate and its calc_values row, the
-- confirmed order amount and the current approved budget. An adopted
-- version is never rewritten: later actuals and corrections only flag
-- 見込更新要 and a new version is adopted (spec §6.6).
--
-- actual_complete = 0 when, at adoption, approved hours lacked a rate or
-- hours / direct costs up to the base date waited for approval or were
-- provisional (暫定・不足あり).
--
-- status MUST match `cost_domain::forecast` (draft | adopted), cost_type
-- `cost_domain::forecast::CostType`.
CREATE TABLE forecast_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    version_no BIGINT,
    status TEXT NOT NULL CHECK (status IN ('draft','adopted')),
    base_date TEXT NOT NULL,
    planned_end TEXT,
    reason TEXT,
    forecast_rate BIGINT,
    applied_calc_value_id BIGINT REFERENCES calc_values(id),
    order_amount BIGINT,
    budget_version_id BIGINT REFERENCES budget_versions(id),
    budget_total BIGINT,
    actual_total BIGINT,
    committed_total BIGINT,
    remaining_total BIGINT,
    cost_total BIGINT,
    actual_complete BIGINT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    adopted_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    adopted_at TEXT,
    row_version BIGINT NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (now()::text),
    updated_at TEXT NOT NULL DEFAULT (now()::text),
    CHECK ((status = 'draft' AND version_no IS NULL AND adopted_at IS NULL
            AND cost_total IS NULL)
        OR (status = 'adopted' AND version_no IS NOT NULL AND adopted_at IS NOT NULL
            AND actual_total IS NOT NULL AND committed_total IS NOT NULL
            AND remaining_total IS NOT NULL AND cost_total IS NOT NULL
            AND actual_complete IS NOT NULL))
);

CREATE UNIQUE INDEX forecast_versions_no ON forecast_versions (project_id, version_no);
CREATE UNIQUE INDEX forecast_versions_one_draft ON forecast_versions (project_id)
    WHERE status = 'draft';

-- A draft's lines are the remaining input only (actual / committed NULL).
-- Adoption rewrites them as the merged set: every phase × cost type with an
-- actual, a commitment or a remaining input, the snapshot columns filled.
-- phase_id NULL = no phase (案件全体).
CREATE TABLE forecast_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_version_id BIGINT NOT NULL REFERENCES forecast_versions(id),
    line_no BIGINT NOT NULL,
    phase_id BIGINT REFERENCES phases(id),
    cost_type TEXT NOT NULL
        CHECK (cost_type IN ('labor','material','outsource','travel','other')),
    actual_amount BIGINT,
    committed_amount BIGINT,
    remaining_minutes BIGINT,
    other_remaining BIGINT,
    labor_remaining BIGINT,
    CHECK (remaining_minutes IS NULL OR (cost_type = 'labor' AND remaining_minutes > 0)),
    CHECK (other_remaining IS NULL OR (cost_type <> 'labor' AND other_remaining >= 0))
);

CREATE UNIQUE INDEX forecast_lines_key
    ON forecast_lines (forecast_version_id, COALESCE(phase_id, 0), cost_type);
