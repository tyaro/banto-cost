-- banto-cost P6b (docs/project/design.md §3.5.2, spec §7 / §9, T11): 月次締め.
--
-- closing_periods has one row per month ('YYYY-MM') that anyone has touched
-- through the closing gate: 'open' (never closed, or a write created the
-- row), 'closed' or 'reopened'. A writer of hours, direct costs or revenue
-- recognitions upserts the 'open' row of its business month and reads it
-- back in its own transaction (FOR SHARE on Postgres); the closer upserts the
-- same row and locks it (FOR UPDATE) before counting the month's unapproved
-- records, so a write and a close of the same month never pass each other
-- (T13). status MUST match `cost_domain::closing::MonthStatus`.
CREATE TABLE closing_periods (
    month TEXT PRIMARY KEY CHECK (length(month) = 7),
    status TEXT NOT NULL CHECK (status IN ('open','closed','reopened')),
    row_version BIGINT NOT NULL DEFAULT 1,
    updated_at TEXT NOT NULL DEFAULT (now()::text)
);

-- Every close and reopen, never rewritten or deleted. A reopen carries its
-- reason (required); a close has none.
CREATE TABLE closing_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month TEXT NOT NULL REFERENCES closing_periods(month),
    action TEXT NOT NULL CHECK (action IN ('close','reopen')),
    reason TEXT,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT (now()::text),
    CHECK (action = 'close' OR reason IS NOT NULL)
);

CREATE INDEX closing_events_month ON closing_events (month);

-- The month's figures of each project as they stood when it was closed
-- (spec §9: 締め時点の数値を保存し、訂正後の最新値との違いを確認できる).
-- One set per close event; projects with all-zero figures are not stored.
CREATE TABLE closing_snapshot_rows (
    event_id BIGINT NOT NULL REFERENCES closing_events(id),
    project_id BIGINT NOT NULL REFERENCES projects(id),
    labor_cost BIGINT NOT NULL,
    labor_missing BIGINT NOT NULL,
    direct_cost BIGINT NOT NULL,
    revenue BIGINT NOT NULL,
    PRIMARY KEY (event_id, project_id)
);
