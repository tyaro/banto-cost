-- banto-cost (docs/project/design.md §10.9, 2026-11-14): 個人別の時間原価単価.
-- Postgres twin of migrations-sqlite/0028_person_rates.sql (see there).

CREATE TABLE person_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    project_id BIGINT REFERENCES projects(id),
    valid_from TEXT NOT NULL,
    value BIGINT CHECK (value IS NULL OR value > 0),
    version_no BIGINT NOT NULL,
    reason TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT (now()::text)
);

CREATE UNIQUE INDEX person_rates_valid_from
    ON person_rates (user_id, COALESCE(project_id, 0), valid_from);
CREATE UNIQUE INDEX person_rates_version
    ON person_rates (user_id, COALESCE(project_id, 0), version_no);
CREATE INDEX person_rates_project ON person_rates (project_id);

CREATE TRIGGER person_rates_dates BEFORE INSERT OR UPDATE OF valid_from ON person_rates
    FOR EACH ROW EXECUTE FUNCTION banto_cost_check_dates('date', 'valid_from');

ALTER TABLE time_entries ADD COLUMN applied_person_rate_id BIGINT REFERENCES person_rates(id);
